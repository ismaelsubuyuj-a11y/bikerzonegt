create extension if not exists pgcrypto;

-- 1) Tablas (si ya existen, solo agrega lo que falte)
create table if not exists public.proyectos (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nombre text not null default 'Sin nombre',
  datos jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cotizaciones (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  numero bigint generated by default as identity,
  cliente text not null default '',
  datos jsonb not null default '{}'::jsonb,
  fecha timestamptz not null default now()
);

-- 2) Columnas que pudieran faltar en tablas existentes
alter table public.proyectos add column if not exists user_id uuid default auth.uid() references auth.users(id) on delete cascade;
alter table public.proyectos add column if not exists nombre text not null default 'Sin nombre';
alter table public.proyectos add column if not exists datos jsonb not null default '{}'::jsonb;
alter table public.proyectos add column if not exists updated_at timestamptz not null default now();
alter table public.cotizaciones add column if not exists user_id uuid default auth.uid() references auth.users(id) on delete cascade;
alter table public.cotizaciones add column if not exists cliente text not null default '';
alter table public.cotizaciones add column if not exists datos jsonb not null default '{}'::jsonb;
alter table public.cotizaciones add column if not exists fecha timestamptz not null default now();

create index if not exists proyectos_user_idx on public.proyectos(user_id, updated_at desc);
create index if not exists cotizaciones_user_idx on public.cotizaciones(user_id, numero desc);

-- 3) Actualiza updated_at automáticamente
create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists proyectos_touch on public.proyectos;
create trigger proyectos_touch before update on public.proyectos
  for each row execute function public.touch_updated_at();

-- 4) Seguridad: Row Level Security. Cada usuario solo ve y modifica lo suyo.
alter table public.proyectos enable row level security;
alter table public.cotizaciones enable row level security;

-- Quita acceso al rol anónimo (no autenticado)
revoke all on public.proyectos from anon;
revoke all on public.cotizaciones from anon;
grant select, insert, update, delete on public.proyectos to authenticated;
grant select, insert, update, delete on public.cotizaciones to authenticated;

drop policy if exists "proyectos: solo dueño" on public.proyectos;
create policy "proyectos: solo dueño" on public.proyectos
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "cotizaciones: solo dueño" on public.cotizaciones;
create policy "cotizaciones: solo dueño" on public.cotizaciones
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- 5) Evita que alguien cambie el dueño de un registro
create or replace function public.lock_owner()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.user_id <> old.user_id then
    raise exception 'No se puede cambiar el dueño del registro';
  end if;
  return new;
end $$;

drop trigger if exists proyectos_lock_owner on public.proyectos;
create trigger proyectos_lock_owner before update on public.proyectos
  for each row execute function public.lock_owner();

drop trigger if exists cotizaciones_lock_owner on public.cotizaciones;
create trigger cotizaciones_lock_owner before update on public.cotizaciones
  for each row execute function public.lock_owner();

-- 6) Verificación: debe mostrar rls_enabled = true en ambas tablas
select relname as tabla, relrowsecurity as rls_enabled
from pg_class
where relnamespace = 'public'::regnamespace and relname in ('proyectos','cotizaciones');
